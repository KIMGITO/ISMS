#!/usr/bin/env python3
"""
Draws the KayKay's milk-glass notification icons.

  ic_stat_milk_alarm.xml   white silhouette for the status bar (24dp, no colour, no gradient)
  ic_milk_glass_large.xml  coloured version for the notification large icon and the alarm screen

The glass is tilted and the milk surface stays level (gravity), with milk spilling over the low
lip and drops flying off. Geometry is computed here so both icons share one shape.

Run:  python3 scripts/milk-icon/generate.py [preview_dir]
"""
import math
import os
import sys

ROOT = os.path.abspath(os.path.join(os.path.dirname(__file__), "..", ".."))
RES = os.path.join(ROOT, "android", "app", "src", "main", "res")

TILT = 21.0                    # degrees, clockwise: the top leans right
PIVOT = (5.9, 21.6)            # rotate about the base
# Upright glass, in the 24x24 grid before tilting.
TOP_Y, BOT_Y = 7.6, 21.6
TOP_HALF, BOT_HALF = 4.2, 3.1
CX = 5.9
WALL = 1.3                     # glass wall thickness
BASE = 1.8                     # thicker base, like a real tumbler
GAP = 0.85                     # clear glass between the wall and the milk, so both read


def rot(p):
    a = math.radians(TILT)
    x, y = p[0] - PIVOT[0], p[1] - PIVOT[1]
    return (PIVOT[0] + x * math.cos(a) - y * math.sin(a), PIVOT[1] + x * math.sin(a) + y * math.cos(a))


def glass(inset=0.0, base=0.0):
    return [rot(p) for p in [
        (CX - TOP_HALF + inset, TOP_Y),
        (CX + TOP_HALF - inset, TOP_Y),
        (CX + BOT_HALF - inset, BOT_Y - base),
        (CX - BOT_HALF + inset, BOT_Y - base),
    ]]


def clip_below(poly, y_line):
    """Keeps the part of the polygon below the horizontal line (larger y)."""
    out = []
    n = len(poly)
    for i in range(n):
        a, b = poly[i], poly[(i + 1) % n]
        ina, inb = a[1] >= y_line, b[1] >= y_line
        if ina:
            out.append(a)
        if ina != inb:
            t = (y_line - a[1]) / (b[1] - a[1])
            out.append((a[0] + t * (b[0] - a[0]), y_line))
    return out


def poly_path(pts):
    return "M" + " L".join(f"{x:.2f},{y:.2f}" for x, y in pts) + " Z"


def circle_path(cx, cy, r):
    return (f"M{cx - r:.2f},{cy:.2f} a{r:.2f},{r:.2f} 0 1,0 {2 * r:.2f},0 "
            f"a{r:.2f},{r:.2f} 0 1,0 {-2 * r:.2f},0 Z")


def drop_path(cx, cy, r, angle_deg):
    """A teardrop pointing back along its flight (angle = direction of travel)."""
    a = math.radians(angle_deg + 180)
    tip = (cx + math.cos(a) * r * 2.3, cy + math.sin(a) * r * 2.3)
    # tangent points on the circle for the tail
    side = math.radians(angle_deg + 180)
    p1 = (cx + math.cos(side + math.pi / 2) * r, cy + math.sin(side + math.pi / 2) * r)
    p2 = (cx + math.cos(side - math.pi / 2) * r, cy + math.sin(side - math.pi / 2) * r)
    return (f"M{tip[0]:.2f},{tip[1]:.2f} L{p1[0]:.2f},{p1[1]:.2f} "
            f"A{r:.2f},{r:.2f} 0 1,1 {p2[0]:.2f},{p2[1]:.2f} Z")


outer = glass()
inner = glass(WALL, BASE)
lip = outer[1]                     # top-right corner after tilting: the low lip
inner_lip = inner[1]
milk_y = inner_lip[1] + 1.0        # just under the low lip: it's about to pour
milk = clip_below(glass(WALL + GAP, BASE + GAP), milk_y)

# Milk pouring over the lip: a curling tongue that leaves the rim.
lx, ly = lip
spill = (f"M{lx - 2.3:.2f},{milk_y + 0.9:.2f} "
         f"C{lx - 1.2:.2f},{milk_y - 0.6:.2f} {lx + 0.2:.2f},{ly - 2.6:.2f} {lx + 2.0:.2f},{ly - 2.2:.2f} "
         f"C{lx + 3.3:.2f},{ly - 1.9:.2f} {lx + 3.4:.2f},{ly - 0.3:.2f} {lx + 2.5:.2f},{ly + 0.2:.2f} "
         f"C{lx + 2.6:.2f},{ly - 0.9:.2f} {lx + 1.5:.2f},{ly - 1.1:.2f} {lx + 0.5:.2f},{ly - 0.2:.2f} "
         f"C{lx - 0.3:.2f},{ly + 0.6:.2f} {lx - 1.0:.2f},{milk_y + 1.0:.2f} {lx - 1.4:.2f},{milk_y + 1.9:.2f} Z")

# Drops flying up and out, getting smaller: three is enough to read at 24dp.
drops = [
    (lx + 5.0, ly - 1.7, 1.25, -20),
    (lx + 3.6, ly - 5.3, 1.05, -55),
    (lx + 6.6, ly - 5.1, 0.85, -35),
]
print("lip", [round(v, 2) for v in lip], "drops max x", round(max(x + r for x, _, r, _ in drops), 2),
      "min y", round(min(y - r * 2.3 for _, y, r, _ in drops), 2))

glass_ring = poly_path(outer) + " " + poly_path(list(reversed(inner)))
milk_path = poly_path(milk)
drop_paths = [drop_path(x, y, r, a) for x, y, r, a in drops]


def vector(paths, comment):
    body = "\n".join(
        f'    <path\n        android:fillColor="{c}"\n'
        + (f'        android:fillType="evenOdd"\n' if even else "")
        + f'        android:pathData="{d}" />'
        for d, c, even in paths)
    return f"""<?xml version="1.0" encoding="utf-8"?>
<!-- {comment}
     Generated by scripts/milk-icon/generate.py: edit the script, not this file. -->
<vector xmlns:android="http://schemas.android.com/apk/res/android"
    android:width="24dp"
    android:height="24dp"
    android:viewportWidth="24"
    android:viewportHeight="24">
{body}
</vector>
"""


# Status bar: Android uses only the alpha channel, so everything is solid white.
stat = vector(
    [(glass_ring, "#FFFFFFFF", True), (milk_path, "#FFFFFFFF", False), (spill, "#FFFFFFFF", False)]
    + [(d, "#FFFFFFFF", False) for d in drop_paths],
    "Status-bar icon: tilted glass of milk with drops splashing out. White on transparent.")

# Large icon: amber disc (the app's brand colour), cream milk, brown glass edge.
AMBER, AMBER_DARK, CREAM, GLASS, BROWN = "#FFF59E0B", "#FFD97706", "#FFFFFFFF", "#59FFFFFF", "#FF78350F"
WALLC = "#FFFEF3C7"
disc = circle_path(12, 12, 12)
large = vector(
    [(disc, AMBER, False),
     (circle_path(12, 13.2, 10.2), "#33B45309", False),
     (poly_path(glass(0.0, 0.0)), GLASS, False),
     (glass_ring, WALLC, True),
     (poly_path(outer) + " " + poly_path(list(reversed(glass(0.42, 0.42)))), BROWN, True),
     (milk_path, CREAM, False), (spill, CREAM, False)]
    + [(d, CREAM, False) for d in drop_paths],
    "Large notification icon and alarm-screen art: the milk glass on the app's amber.")

# Keep the art inside the disc: wrap everything after the two disc paths in a scaled group.
_parts = large.split("    <path", 3)
large = (_parts[0] + "    <path" + _parts[1] + "    <path" + _parts[2]
         + '    <group android:scaleX="0.8" android:scaleY="0.8" android:pivotX="12" android:pivotY="12.6">\n'
         + "    <path" + _parts[3].replace("</vector>", "    </group>\n</vector>"))


def svg(paths, size, bg=None):
    els = ""
    for d, c, even in paths:
        rule = ' fill-rule="evenodd"' if even else ""
        els += f'<path d="{d}" fill="#{c[3:]}" fill-opacity="{int(c[1:3], 16) / 255:.2f}"{rule}/>'
    back = f'<rect width="24" height="24" fill="{bg}"/>' if bg else ""
    return f'<svg xmlns="http://www.w3.org/2000/svg" width="{size}" height="{size}" viewBox="0 0 24 24">{back}{els}</svg>'


if __name__ == "__main__":
    with open(os.path.join(RES, "drawable", "ic_stat_milk_alarm.xml"), "w") as f:
        f.write(stat)
    with open(os.path.join(RES, "drawable", "ic_milk_glass_large.xml"), "w") as f:
        f.write(large)
    print("wrote drawable/ic_stat_milk_alarm.xml and drawable/ic_milk_glass_large.xml")

    if len(sys.argv) > 1:
        out = sys.argv[1]
        os.makedirs(out, exist_ok=True)
        stat_paths = [(glass_ring, "#FFFFFFFF", True), (milk_path, "#FFFFFFFF", False),
                      (spill, "#FFFFFFFF", False)] + [(d, "#FFFFFFFF", False) for d in drop_paths]
        large_paths = [(disc, AMBER, False), (circle_path(12, 13.2, 10.2), "#33B45309", False),
                       (poly_path(glass(0.0, 0.0)), GLASS, False), (glass_ring, WALLC, True), (poly_path(outer) + " " + poly_path(list(reversed(glass(0.42, 0.42)))), BROWN, True),
                       (milk_path, CREAM, False), (spill, CREAM, False)] + [(d, CREAM, False) for d in drop_paths]
        open(os.path.join(out, "stat.svg"), "w").write(svg(stat_paths, 240, "#202124"))
        big = svg(large_paths, 240)
        head, rest = big.split("<path", 1)
        first, second, art = ("<path" + rest).split("/>", 2)
        big = (head + first + "/>" + second + '/><g transform="translate(12 12.6) scale(0.8) translate(-12 -12.6)">'
               + art.replace("</svg>", "</g></svg>"))
        open(os.path.join(out, "large.svg"), "w").write(big)
        print("previews in", out)
