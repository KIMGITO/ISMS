#!/usr/bin/env python3
"""
Builds the animated loading picture: the milk-glass icon (same shapes as generate.py) with
the glass rocking forward, the milk staying level inside it, milk curling over the lip and
drops splashing out in arcs. One SVG with built-in SMIL animation, so it plays in a plain
<img> tag on the app, the boot screen and the website, with no JavaScript.

Writes public/milk-loader.svg (app) and website/public/milk-loader.svg (website).

Run:  python3 scripts/milk-icon/loader.py
"""
import math
import os
import sys

sys.argv = sys.argv[:1]  # generate.py reads argv only under __main__; keep it quiet on import
sys.path.insert(0, os.path.dirname(__file__))
import generate as g  # noqa: E402

OUTLINE = "#D97706"   # amber edge on the milk so it reads on light and dark backgrounds
DUR = 2.2          # seconds for one pour
REST, PEAK = -6.0, 8.0   # extra tilt (degrees) on top of the icon's own lean
px, py = g.PIVOT


def f(v):
    return f"{v:.2f}"


def rot_about(p, deg, c=g.PIVOT):
    a = math.radians(deg)
    x, y = p[0] - c[0], p[1] - c[1]
    return (c[0] + x * math.cos(a) - y * math.sin(a), c[1] + x * math.sin(a) + y * math.cos(a))


def ease():
    # gentle in-out for every segment
    return "0.45 0 0.55 1"


# Glass rocks: rest -> tips forward -> holds while it pours -> settles back.
TILT_KT = "0;0.38;0.6;1"
tilt_vals = f"{REST} {px} {py};{PEAK} {px} {py};{PEAK} {px} {py};{REST} {px} {py}"
# Milk counter-rotates so its surface stays level, lagging a touch so it sloshes.
LEVEL_KT = "0;0.44;0.66;1"
level_vals = f"{-REST} {px} {py};{-PEAK} {px} {py};{-PEAK} {px} {py};{-REST} {px} {py}"
splines3 = ";".join([ease()] * 3)

outer, inner = g.outer, g.inner
lx, ly = g.lip
milk_y = g.milk_y

# Level milk: a big block whose top edge is the surface, clipped by the inside of the glass.
milk_block = f"M-12,{f(milk_y)} H36 V40 H-12 Z"
milk_clip = g.poly_path(g.glass(g.WALL + g.GAP, g.BASE + g.GAP))

# The tip of the milk curl while the glass is fully tipped: drops leave from here.
sx, sy = rot_about((lx + 2.4, ly - 1.6), PEAK)

# Each bead flies up and out, then gravity bends it down: (peak dx, dy, landing dx, dy,
# radius, start, end), times as fractions of the loop.
DROPS = [
    (3.0, -7.0, 6.0, 3.0, 1.10, 0.40, 0.80),
    (1.6, -9.0, 3.2, 1.0, 0.80, 0.43, 0.86),
    (5.0, -4.6, 8.4, 5.0, 0.95, 0.45, 0.84),
    (4.0, -10.0, 7.4, -1.0, 0.65, 0.48, 0.92),
    (6.4, -3.0, 9.6, 7.0, 0.70, 0.52, 0.90),
    (0.8, -6.2, 1.8, 2.0, 0.55, 0.54, 0.88),
    (2.4, -11.0, 4.6, -3.0, 0.50, 0.56, 0.95),
]


def drop_el(dx1, dy1, dx2, dy2, r, t0, t1):
    # control point twice the peak height so the curve actually reaches the peak
    path = f"M0,0 Q{f(dx1 * 0.8)},{f(1.3 * dy1)} {f(dx2 * 0.8)},{f(dy2)}"
    fade_in, fade_out = t0 + 0.03, t1 - 0.12
    return (
        f'<circle cx="{f(sx)}" cy="{f(sy)}" r="{f(r)}" fill="#FFFFFF" stroke="{OUTLINE}" stroke-width="0.3" opacity="0">'
        f'<animateMotion dur="{DUR}s" repeatCount="indefinite" path="{path}" '
        f'calcMode="spline" keyPoints="0;0;1;1" keyTimes="0;{t0};{t1};1" '
        f'keySplines="0 0 1 1;0.15 0.5 0.6 1;0 0 1 1"/>'
        f'<animate attributeName="opacity" dur="{DUR}s" repeatCount="indefinite" '
        f'values="0;0;1;1;0;0" keyTimes="0;{t0};{f(fade_in)};{f(fade_out)};{t1};1"/>'
        f'<animate attributeName="r" dur="{DUR}s" repeatCount="indefinite" '
        f'values="{f(r * 0.5)};{f(r * 0.5)};{f(r)};{f(r * 0.6)};{f(r * 0.6)}" keyTimes="0;{t0};{f(t0 + 0.08)};{t1};1"/>'
        f'</circle>'
    )


# The curl of milk over the lip grows while the glass is tipped, then shrinks back.
spill_grow = (
    f'<animateTransform attributeName="transform" type="scale" dur="{DUR}s" repeatCount="indefinite" '
    f'values="0.01;0.01;1;1;0.01" keyTimes="0;0.28;0.45;0.66;1" calcMode="spline" '
    f'keySplines="0 0 1 1;{ease()};0 0 1 1;{ease()}"/>'
)

CREAM, BROWN, WALLC = "#FFFFFF", "#78350F", "#FEF3C7"
glass_ring = g.glass_ring
brown_edge = g.poly_path(outer) + " " + g.poly_path(list(reversed(g.glass(0.42, 0.42))))

svg = f"""<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 24 24" width="96" height="96" role="img" aria-label="Loading">
<!-- Animated loader. Generated by scripts/milk-icon/loader.py: edit the script, not this file. -->
<defs>
<clipPath id="inside"><path d="{milk_clip}"/></clipPath>
</defs>
<g transform="translate(12 12.6) scale(0.8) translate(-12 -12.6)">
<g>
<animateTransform attributeName="transform" type="rotate" dur="{DUR}s" repeatCount="indefinite" values="{tilt_vals}" keyTimes="{TILT_KT}" calcMode="spline" keySplines="{splines3}"/>
<path d="{g.poly_path(outer)}" fill="#F59E0B" fill-opacity="0.3"/>
<g clip-path="url(#inside)">
<path d="{milk_block}" fill="{CREAM}">
<animateTransform attributeName="transform" type="rotate" dur="{DUR}s" repeatCount="indefinite" values="{level_vals}" keyTimes="{LEVEL_KT}" calcMode="spline" keySplines="{splines3}"/>
</path>
</g>
<path d="{glass_ring}" fill="{WALLC}" fill-rule="evenodd"/>
<path d="{brown_edge}" fill="{BROWN}" fill-rule="evenodd"/>
<g transform="translate({f(lx)} {f(ly)})"><g>{spill_grow}<path d="{g.spill}" fill="{CREAM}" stroke="{OUTLINE}" stroke-width="0.3" stroke-linejoin="round" transform="translate({f(-lx)} {f(-ly)})"/></g></g>
</g>
{"".join(drop_el(*d) for d in DROPS)}
</g>
</svg>
"""

if __name__ == "__main__":
    for rel in ("public/milk-loader.svg", "website/public/milk-loader.svg"):
        with open(os.path.join(g.ROOT, rel), "w") as fh:
            fh.write(svg)
        print("wrote", rel)
