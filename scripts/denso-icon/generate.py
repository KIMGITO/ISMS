#!/usr/bin/env python3
"""
Draws every Denso picture from one shape: a bold "D" with three rising stock bars inside it.

  public/denso.svg                 app icon (amber tile, dark D, white bars)
  public/denso-mark.svg            the mark alone, no tile
  public/denso-animated.svg        intro: the D draws itself, bars rise, the name slides in (plays once);
                                   denso-animated-dark.svg is the same with white text for dark screens
  public/denso-loader.svg          looping loader (works on light and dark)
  public/denso-notification.svg    white silhouette for notifications (24x24, one colour)
  public/icon.png, favicon.png, logo.png, denso-badge.png; website/public favicon, logo and loader
  android: ic_stat_denso.xml (status bar), ic_denso_large.xml (large icon, alarm screen),
           launcher mipmaps (adaptive + legacy + round), splash screens
  src-tauri/icons via `npx tauri icon`

Run from the repo root:  python3 scripts/denso-icon/generate.py
Needs inkscape (SVG -> PNG) and ImageMagick `convert`.
"""
import os
import shutil
import subprocess
import tempfile

ROOT = os.path.abspath(os.path.join(os.path.dirname(__file__), "..", ".."))
PUB = os.path.join(ROOT, "public")
WEB_PUB = os.path.join(ROOT, "website", "public")
RES = os.path.join(ROOT, "android", "app", "src", "main", "res")

AMBER = "#F59E0B"
AMBER_DARK = "#B45309"
INK = "#1C1917"
WHITE = "#FFFFFF"
NIGHT = "#020617"   # the app's loading background (slate-950)

# ---------------------------------------------------------------- geometry (100 x 100 box)
# The D: straight back, half-circle front. Shifted 3 left so it sits optically centred.
OUT_L, OUT_T, OUT_B, OUT_R = 21, 18, 82, 32        # left, top, bottom, front radius
IN_L, IN_T, IN_B, IN_R = 34, 31, 69, 19            # the hole (counter)
ARC_X = 47                                          # where straight edges meet the arcs
BASE = 61                                           # bar baseline
BARS = [(37.5, 43.5, 52), (45.5, 51.5, 45), (53.5, 59.5, 38)]   # (left, right, top), shortest first
BAR_R = 1.2


def f(v):
    return f"{v:.2f}".rstrip("0").rstrip(".")


class T:
    """Maps the 100-box onto a target: x' = ox + x*s."""

    def __init__(self, s=1.0, ox=0.0, oy=0.0):
        self.s, self.ox, self.oy = s, ox, oy

    def x(self, v):
        return f(self.ox + v * self.s)

    def y(self, v):
        return f(self.oy + v * self.s)

    def d(self, v):
        return f(v * self.s)


def d_outer(t):
    return (f"M{t.x(OUT_L)},{t.y(OUT_T)} H{t.x(ARC_X)} "
            f"A{t.d(OUT_R)},{t.d(OUT_R)} 0 0 1 {t.x(ARC_X)},{t.y(OUT_B)} H{t.x(OUT_L)} Z")


def d_counter(t):
    return (f"M{t.x(IN_L)},{t.y(IN_T)} H{t.x(ARC_X)} "
            f"A{t.d(IN_R)},{t.d(IN_R)} 0 0 1 {t.x(ARC_X)},{t.y(IN_B)} H{t.x(IN_L)} Z")


def d_shape(t):
    return d_outer(t) + " " + d_counter(t)


def bar_path(t, l, r, top):
    """Rounded top corners, square bottom (sits on the baseline)."""
    rr = BAR_R
    return (f"M{t.x(l)},{t.y(BASE)} V{t.y(top + rr)} "
            f"A{t.d(rr)},{t.d(rr)} 0 0 1 {t.x(l + rr)},{t.y(top)} H{t.x(r - rr)} "
            f"A{t.d(rr)},{t.d(rr)} 0 0 1 {t.x(r)},{t.y(top + rr)} V{t.y(BASE)} Z")


def bars_path(t):
    return " ".join(bar_path(t, *b) for b in BARS)


# The D as one line through the middle of its stroke, for drawing it on.
MID_W = OUT_L + (IN_L - OUT_L) / 2          # 27.5
MID_T = OUT_T + (IN_T - OUT_T) / 2          # 24.5
MID_B = OUT_B - (OUT_B - IN_B) / 2          # 75.5
MID_R = (OUT_R + IN_R) / 2                  # 25.5
STROKE = IN_L - OUT_L                       # 13
D_CENTRELINE = (f"M{f(MID_W)},{f(MID_T)} H{ARC_X} A{f(MID_R)},{f(MID_R)} 0 0 1 {ARC_X},{f(MID_B)} "
                f"H{f(MID_W)} Z")
D_LENGTH = (ARC_X - MID_W) * 2 + 3.14159265 * MID_R + (MID_B - MID_T)   # ~170.1

HEADER = "<!-- Generated by scripts/denso-icon/generate.py: edit the script, not this file. -->"
EASE = "0.45 0 0.55 1"


# ---------------------------------------------------------------- SVG pictures
def svg_icon(size=1024, shape="tile"):
    """The app icon. shape: tile (rounded square), circle, square (full bleed)."""
    t = T()
    if shape == "circle":
        bg = f'<circle cx="50" cy="50" r="50" fill="{AMBER}"/>'
    elif shape == "square":
        bg = f'<rect width="100" height="100" fill="{AMBER}"/>'
    else:
        bg = f'<rect width="100" height="100" rx="22" fill="{AMBER}"/>'
    # Circles need the mark a little smaller to clear the edge.
    inner = (f'<path d="{d_shape(t)}" fill="{INK}" fill-rule="evenodd"/>'
             f'<path d="{bars_path(t)}" fill="{WHITE}"/>')
    if shape == "circle":
        inner = f'<g transform="translate(50 50) scale(0.86) translate(-50 -50)">{inner}</g>'
    return (f'<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 100 100" width="{size}" height="{size}">\n'
            f'{HEADER}\n<title>Denso</title>\n{bg}\n{inner}\n</svg>\n')


def svg_mark(size=512, colour=AMBER, bar_colour=None):
    t = T()
    bars = (f'<path d="{bars_path(t)}" fill="{bar_colour}"/>' if bar_colour
            else f'<path d="{bars_path(t)}" fill="{colour}"/>')
    return (f'<svg xmlns="http://www.w3.org/2000/svg" viewBox="14 14 72 72" width="{size}" height="{size}">\n'
            f'{HEADER}\n<title>Denso</title>\n'
            f'<path d="{d_shape(t)}" fill="{colour}" fill-rule="evenodd"/>\n{bars}\n</svg>\n')


def svg_android_foreground():
    """Adaptive-icon foreground: the mark on transparent, inside the 66/108 safe circle."""
    s = 0.70 * 108 / 100
    o = 54 - 50 * s
    t = T(s, o, o)
    return (f'<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 108 108" width="432" height="432">'
            f'<path d="{d_shape(t)}" fill="{INK}" fill-rule="evenodd"/>'
            f'<path d="{bars_path(t)}" fill="{WHITE}"/></svg>')


def svg_notification(size=24, colour=WHITE, bg=None):
    """One-colour silhouette: the D with its hole, bars solid inside the hole."""
    s = 21 / 64                               # the 64-unit mark fills 21 of 24
    t = T(s, 12 - 50 * s, 12 - 50 * s)
    back = f'<rect width="24" height="24" fill="{bg}"/>' if bg else ""
    return (f'<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 24 24" width="{size}" height="{size}">\n'
            f'{HEADER}\n<title>Denso</title>\n{back}'
            f'<path d="{d_shape(t)}" fill="{colour}" fill-rule="evenodd"/>\n'
            f'<path d="{bars_path(t)}" fill="{colour}"/>\n</svg>\n')


def bar_anim(i, l, r, top, colour, dur, values, key_times, begin="0s", repeat="indefinite", fill=None):
    """A bar that grows from its baseline (scaleY about BASE)."""
    splines = ";".join([EASE] * (len(values) - 1))
    vals = ";".join(f"1 {v}" for v in values)
    freeze = f' fill="{fill}"' if fill else ""
    return (f'<g transform="translate(0 {BASE})"><path d="{bar_path(T(1, 0, -BASE), l, r, top)}" fill="{colour}" '
            f'transform="scale(1 {values[0]})">'
            f'<animateTransform attributeName="transform" type="scale" dur="{dur}" begin="{begin}" '
            f'repeatCount="{repeat}" values="{vals}" keyTimes="{key_times}" calcMode="spline" '
            f'keySplines="{splines}"{freeze}/></path></g>')


def svg_loader(size=96):
    """Loops: a bright piece runs round a faint D while the bars rise and fall in a wave."""
    dur = "1.8s"
    L = D_LENGTH
    seg = L * 0.32
    parts = [
        f'<path d="{D_CENTRELINE}" fill="none" stroke="{AMBER}" stroke-opacity="0.22" stroke-width="{STROKE}" stroke-linejoin="miter"/>',
        f'<path d="{D_CENTRELINE}" fill="none" stroke="{AMBER}" stroke-width="{STROKE}" '
        f'stroke-linejoin="miter" stroke-dasharray="{f(seg)} {f(L - seg)}" stroke-dashoffset="0">'
        f'<animate attributeName="stroke-dashoffset" dur="{dur}" repeatCount="indefinite" values="0;{f(-L)}" '
        f'calcMode="linear"/></path>',
    ]
    for i, (l, r, top) in enumerate(BARS):
        # Each bar's wave starts a little later than the one before.
        lo = 0.25
        parts.append(bar_anim(i, l, r, top, AMBER, dur, [lo, 1, lo], "0;0.5;1", begin=f"{-1.8 + i * 0.22:.2f}s"))
    return (f'<svg xmlns="http://www.w3.org/2000/svg" viewBox="14 14 72 72" width="{size}" height="{size}" '
            f'role="img" aria-label="Loading">\n{HEADER}\n' + "\n".join(parts) + "\n</svg>\n")


def svg_animated(width=560, text=INK):
    """Plays once and holds: the D draws itself, fills, the bars rise one by one, then 'Denso' slides in."""
    L = D_LENGTH
    t = T()
    draw = (f'<path d="{D_CENTRELINE}" fill="none" stroke="{AMBER}" stroke-width="{STROKE}" stroke-linejoin="miter" '
            f'stroke-dasharray="{f(L)}" stroke-dashoffset="{f(L)}">'
            f'<animate attributeName="stroke-dashoffset" dur="0.8s" begin="0s" values="{f(L)};0" calcMode="spline" '
            f'keyTimes="0;1" keySplines="{EASE}" fill="freeze"/>'
            f'<animate attributeName="opacity" dur="0.2s" begin="0.8s" values="1;0" fill="freeze"/></path>')
    solid = (f'<path d="{d_shape(t)}" fill="{AMBER}" fill-rule="evenodd" opacity="0">'
             f'<animate attributeName="opacity" dur="0.2s" begin="0.75s" values="0;1" fill="freeze"/></path>')
    bars = []
    for i, (l, r, top) in enumerate(BARS):
        begin = f"{0.85 + i * 0.15:.2f}s"
        bars.append(bar_anim(i, l, r, top, AMBER, "0.5s", [0, 1.12, 1], "0;0.7;1", begin=begin,
                             repeat="1", fill="freeze"))
    word = (f'<text x="96" y="66" font-family="Poppins, \'Segoe UI\', system-ui, -apple-system, Roboto, sans-serif" '
            f'font-size="46" font-weight="700" letter-spacing="-1" fill="{text}" opacity="0">Denso'
            f'<animate attributeName="opacity" dur="0.45s" begin="1.35s" values="0;1" fill="freeze"/>'
            f'<animateTransform attributeName="transform" type="translate" dur="0.45s" begin="1.35s" '
            f'values="-14 0;0 0" calcMode="spline" keyTimes="0;1" keySplines="{EASE}" fill="freeze"/></text>')
    return (f'<svg xmlns="http://www.w3.org/2000/svg" viewBox="14 14 228 72" width="{width}" '
            f'height="{round(width * 72 / 228)}" role="img" aria-label="Denso">\n{HEADER}\n'
            + "\n".join([draw, solid] + bars + [word]) + "\n</svg>\n")


# ---------------------------------------------------------------- Android vector drawables
def vector(paths, comment, size=24, viewport=24):
    body = "\n".join(
        f'    <path\n        android:fillColor="{c}"\n' + (f'        android:fillType="evenOdd"\n' if eo else "")
        + f'        android:pathData="{d}" />'
        for c, d, eo in paths)
    return (f'<?xml version="1.0" encoding="utf-8"?>\n<!-- {comment}\n'
            f'     Generated by scripts/denso-icon/generate.py: edit the script, not this file. -->\n'
            f'<vector xmlns:android="http://schemas.android.com/apk/res/android"\n'
            f'    android:width="{size}dp"\n    android:height="{size}dp"\n'
            f'    android:viewportWidth="{viewport}"\n    android:viewportHeight="{viewport}">\n{body}\n</vector>\n')


def android_vectors():
    s = 21 / 64
    t = T(s, 12 - 50 * s, 12 - 50 * s)
    stat = vector([("#FFFFFFFF", d_shape(t), True), ("#FFFFFFFF", bars_path(t), False)],
                  "Status-bar icon: the Denso D with rising bars. White on transparent.")
    s2 = 15 / 64
    t2 = T(s2, 12 - 50 * s2, 12 - 50 * s2)
    circle = "M12,0 a12,12 0 1,0 0.01,0 Z"
    large = vector([("#FFF59E0B", circle, False), ("#FF1C1917", d_shape(t2), True),
                    ("#FFFFFFFF", bars_path(t2), False)],
                   "Large notification icon and alarm-screen art: the Denso mark on amber.", size=96)
    with open(os.path.join(RES, "drawable", "ic_stat_denso.xml"), "w") as fh:
        fh.write(stat)
    with open(os.path.join(RES, "drawable", "ic_denso_large.xml"), "w") as fh:
        fh.write(large)


# ---------------------------------------------------------------- rasters
def png(svg_text, out, size, tmp, background=None):
    src = os.path.join(tmp, "in.svg")
    with open(src, "w") as fh:
        fh.write(svg_text)
    cmd = ["inkscape", src, "--export-type=png", f"--export-filename={out}", f"--export-width={size}",
           f"--export-height={size}"]
    if background:
        cmd += [f"--export-background={background}", "--export-background-opacity=1"]
    subprocess.run(cmd, check=True, stdout=subprocess.DEVNULL, stderr=subprocess.DEVNULL)


def splash(icon_png, out, w, h, bg):
    side = round(min(w, h) * 0.28)
    subprocess.run(["convert", "-size", f"{w}x{h}", f"xc:{bg}", "(", icon_png, "-resize", f"{side}x{side}", ")",
                    "-gravity", "center", "-composite", out], check=True)


def main():
    def write(path, text):
        with open(path, "w") as fh:
            fh.write(text)

    write(os.path.join(PUB, "denso.svg"), svg_icon(512))
    write(os.path.join(PUB, "denso-mark.svg"), svg_mark())
    write(os.path.join(PUB, "denso-animated.svg"), svg_animated())                 # for light backgrounds
    write(os.path.join(PUB, "denso-animated-dark.svg"), svg_animated(text=WHITE))  # for dark backgrounds
    write(os.path.join(PUB, "denso-loader.svg"), svg_loader())
    write(os.path.join(PUB, "denso-notification.svg"), svg_notification())
    android_vectors()

    tmp = tempfile.mkdtemp()
    try:
        master = os.path.join(tmp, "master.png")
        png(svg_icon(1024), master, 1024, tmp)
        shutil.copy(master, os.path.join(PUB, "icon.png"))
        png(svg_icon(512), os.path.join(PUB, "favicon.png"), 512, tmp)
        png(svg_icon(128), os.path.join(PUB, "logo.png"), 128, tmp)
        # Web notification badge: Chrome uses only the alpha, so the white silhouette.
        png(svg_notification(96), os.path.join(PUB, "denso-badge.png"), 96, tmp)
        if os.path.isdir(WEB_PUB):
            shutil.copy(os.path.join(PUB, "favicon.png"), os.path.join(WEB_PUB, "favicon.png"))
            shutil.copy(os.path.join(PUB, "logo.png"), os.path.join(WEB_PUB, "logo.png"))
            shutil.copy(os.path.join(PUB, "denso-loader.svg"), os.path.join(WEB_PUB, "denso-loader.svg"))

        # Android launcher: adaptive (background + foreground) and legacy square/round.
        dens = {"ldpi": 0.75, "mdpi": 1, "hdpi": 1.5, "xhdpi": 2, "xxhdpi": 3, "xxxhdpi": 4}
        fg = svg_android_foreground()
        bg = (f'<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 108 108">'
              f'<rect width="108" height="108" fill="{AMBER}"/></svg>')
        for name, k in dens.items():
            d = os.path.join(RES, f"mipmap-{name}")
            os.makedirs(d, exist_ok=True)
            png(fg, os.path.join(d, "ic_launcher_foreground.png"), round(108 * k), tmp)
            png(bg, os.path.join(d, "ic_launcher_background.png"), round(108 * k), tmp)
            png(svg_icon(48, "tile"), os.path.join(d, "ic_launcher.png"), round(48 * k), tmp)
            png(svg_icon(48, "circle"), os.path.join(d, "ic_launcher_round.png"), round(48 * k), tmp)

        # Splash screens: the icon in the middle, white by day, the app's dark blue at night.
        for folder in sorted(os.listdir(RES)):
            p = os.path.join(RES, folder, "splash.png")
            if not (folder.startswith("drawable") and os.path.exists(p)):
                continue
            w, h = map(int, subprocess.run(["identify", "-format", "%w %h", p], check=True,
                                           capture_output=True, text=True).stdout.split())
            splash(master, p, w, h, NIGHT if "night" in folder else WHITE)
    finally:
        shutil.rmtree(tmp)

    # Desktop icons (ico, icns, pngs, Windows store logos) from the master.
    subprocess.run(["npx", "tauri", "icon", os.path.join(PUB, "icon.png")], cwd=ROOT, check=True)


if __name__ == "__main__":
    main()
